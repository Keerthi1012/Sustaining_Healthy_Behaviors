function withGuidance(actions, domain) {
    const catalog = GENERATED_HABIT_CATALOGS[domain] ?? null;

    for (const action of actions) {
        const generated = catalog?.habits?.[action.id] ?? null;

        if (generated) {
            action.clinicalBasis = generated.clinicalBasis;
            action.limits = generated.limits || action.limits;
            action.safety = generated.safety || action.safety;
            action.progressionLevels = generated.progressionLevels;
            action.progressionPolicy = generated.progressionPolicy;
        } else {
            action.progressionLevels = action.progressionLevels ?? [];
        }

        action.boundaries = catalog?.boundaries ?? null;
        action.safetyRules = catalog?.safetyRules ?? null;
        action.catalogVersion = catalog?.catalogVersion ?? null;
        action.catalogReviewedAt = catalog?.reviewedAt ?? null;
    }

    return actions;
}

export const ACTIONS_BY_GOAL = {
    movement: withGuidance(MOVEMENT_ACTIONS, "movement"),
    sleep: withGuidance(SLEEP_ACTIONS, "sleep"),
    nutrition: withGuidance(NUTRITION_ACTIONS, "nutrition"),
    smoking: withGuidance(SMOKING_ACTIONS, "smoking"),
};

export function getActionsForGoal(goalId) {
    return ACTIONS_BY_GOAL[goalId] ?? [];
}

export function getActionById(actionId) {
    return Object.values(ACTIONS_BY_GOAL)
        .flat()
        .find((action) => action.id === actionId);
}
